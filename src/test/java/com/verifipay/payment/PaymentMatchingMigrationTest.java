package com.verifipay.payment;

import org.flywaydb.core.Flyway;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.SingleConnectionDataSource;
import org.springframework.test.context.ActiveProfiles;

import javax.sql.DataSource;
import java.time.LocalDateTime;
import java.util.UUID;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
@ActiveProfiles("test")
class PaymentMatchingMigrationTest {
    @Autowired DataSource dataSource;

    @Test
    void v10PreservesLegacyEventsVerificationsAndUnknownCancellationDates() throws Exception {
        String schema = "matching_migration_" + UUID.randomUUID().toString().replace("-", "");
        try (var connection = dataSource.getConnection()) {
            assertTrue(connection.getMetaData().getURL().contains("test"), "Migration test requires a test database");
            var jdbc = new JdbcTemplate(new SingleConnectionDataSource(connection, true));
            try {
                Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema)
                        .target("9").load().migrate();
                connection.setSchema(schema);
                var company = jdbc.queryForObject("INSERT INTO companies(name) VALUES ('Historical') RETURNING id", Long.class);
                var branch = jdbc.queryForObject("INSERT INTO branches(company_id, name) VALUES (?, 'Historical') RETURNING id", Long.class, company);
                var cashier = jdbc.queryForObject("""
                        INSERT INTO users(company_id, branch_id, name, email, password, role)
                        VALUES (?, ?, 'Historical', 'migration@example.test', 'unused', 'CASHIER') RETURNING id
                        """, Long.class, company, branch);
                var local = LocalDateTime.of(2025, 1, 1, 14, 0);
                var consumed = jdbc.queryForObject("""
                        INSERT INTO payment_events(company_id, branch_id, method, amount, occurred_at, consumed, source_event_id)
                        VALUES (?, ?, 'YAPE', 80, ?, true, 'historical-source') RETURNING id
                        """, Long.class, company, branch, local);
                jdbc.update("INSERT INTO payment_events(company_id, branch_id, method, amount, occurred_at) VALUES (?, ?, 'YAPE', 80, ?)", company, branch, local);
                jdbc.update("""
                        INSERT INTO verifications(company_id, branch_id, cashier_id, payment_event_id, method, amount, status)
                        VALUES (?, ?, ?, ?, 'YAPE', 80, 'DETECTED')
                        """, company, branch, cashier, consumed);
                jdbc.update("""
                        INSERT INTO payment_requests(company_id, cashier_id, amount, status, client_request_id, created_at, expires_at)
                        VALUES (?, ?, 80, 'CANCELLED', 'historical-cancellation', '2025-01-01T19:00:00Z', '2025-01-01T19:05:00Z')
                        """, company, cashier);
                var beforeEvents = jdbc.queryForList("SELECT id, company_id, branch_id, amount, occurred_at, created_at, consumed, source_event_id FROM payment_events ORDER BY id");
                var beforeVerifications = jdbc.queryForList("SELECT * FROM verifications ORDER BY id");
                var beforeRequests = jdbc.queryForList("SELECT id, status, created_at, expires_at, paid_at FROM payment_requests ORDER BY id");
                var result = Flyway.configure().dataSource(dataSource).schemas(schema).defaultSchema(schema).load().migrate();
                assertEquals(1, result.migrationsExecuted);
                assertEquals(beforeEvents, jdbc.queryForList("SELECT id, company_id, branch_id, amount, occurred_at, created_at, consumed, source_event_id FROM payment_events ORDER BY id"));
                assertEquals(beforeVerifications, jdbc.queryForList("SELECT * FROM verifications ORDER BY id"));
                assertEquals(beforeRequests, jdbc.queryForList("SELECT id, status, created_at, expires_at, paid_at FROM payment_requests ORDER BY id"));
                assertEquals(0L, jdbc.queryForObject("SELECT count(*) FROM payment_events WHERE matching_status IS NOT NULL OR occurred_at_instant IS NOT NULL OR payment_request_id IS NOT NULL", Long.class));
                assertEquals(0L, jdbc.queryForObject("SELECT count(*) FROM payment_requests WHERE cancelled_at IS NOT NULL", Long.class));
                assertEquals(0L, jdbc.queryForObject("SELECT count(*) FROM payment_match_candidates", Long.class));
            } finally {
                connection.setSchema("public");
                // Only the schema generated by this test is removed; no shared records are deleted.
                jdbc.execute("DROP SCHEMA IF EXISTS " + schema + " CASCADE");
            }
        }
    }
}
